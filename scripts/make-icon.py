#!/usr/bin/env python3
# Regenerate the Android launcher vectors from the designed desktop
# icon (assets/icons/app-icon.svg in the MyWhisper repo) so the phone
# ships the same mark. Re-run after icon redesigns; outputs go
# straight into android/app/src/main/res/drawable/.
import re
import sys

DESK = (
    "/home/aaronroque/.t3/worktrees/MyWhisper/t3code-8d7dc4a2/assets/icons/app-icon.svg"
)
OUT = "/home/aaronroque/Projects/MyWhisperMobile/android/app/src/main/res/drawable"


def rrect(x, y, w, h, r):
    hw, hh = w - 2 * r, h - 2 * r
    return (
        f"M{x:g},{y:g}h{hw:g}"
        f"a{r:g},{r:g} 0 0,1 {r:g},{r:g}"
        f"v{hh:g}a{r:g},{r:g} 0 0,1 {-r:g},{r:g}"
        f"h{-hw:g}a{r:g},{r:g} 0 0,1 {-r:g},{-r:g}"
        f"v{-hh:g}a{r:g},{r:g} 0 0,1 {r:g},{-r:g}z"
    )


GRAD = """<gradient
                    android:startX="627"
                    android:startY="273"
                    android:endX="627"
                    android:endY="953"
                    android:type="linear">
                    <item android:offset="0" android:color="#3EF2FD" />
                    <item android:offset="0.34" android:color="#3CCAFD" />
                    <item android:offset="0.68" android:color="#3D93FC" />
                    <item android:offset="1" android:color="#5B68FC" />
                </gradient>"""


def grad_path(d):
    return (
        f'<path android:pathData="{d}" android:fillColor="#FF3CCAFD">\n{GRAD}\n</path>'
    )


def main():
    svg = open(DESK).read()
    rects = re.findall(
        r"<rect x=\"([\d.]+)\" y=\"([\d.]+)\" width=\"([\d.]+)\" height=\"([\d.]+)\" rx=\"([\d.]+)\" fill=\"url\(#tile\)\"/>",
        svg,
    )
    assert len(rects) == 1, rects
    tx, ty, tw, th, tr = map(float, rects[0])
    marks = re.findall(
        r"<rect x=\"([\d.]+)\" y=\"([\d.]+)\" width=\"([\d.]+)\" height=\"([\d.]+)\" rx=\"([\d.]+)\"/>",
        svg,
    )
    swoosh = re.search(r"<path d=\"(M 634.*?)\"/>", svg, re.S).group(1)
    assert len(marks) == 4, marks

    bg = f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:pathData="{rrect(tx * 108 / 1254, ty * 108 / 1254, tw * 108 / 1254, th * 108 / 1254, tr * 108 / 1254)}"
        android:fillColor="#FF141D2A">
        <gradient
            android:startX="12.9"
            android:startY="8.2"
            android:endX="93.9"
            android:endY="101.6"
            android:type="linear">
            <item android:offset="0" android:color="#202B3D" />
            <item android:offset="0.5" android:color="#141D2A" />
            <item android:offset="1" android:color="#0A111C" />
        </gradient>
    </path>
</vector>
'''
    open(f"{OUT}/ic_launcher_background.xml", "w").write(bg)

    # Mark scaled into the adaptive safe zone (scale 0.07 about the
    # mark bbox center mapped to 54,54).
    s = 0.07
    cx, cy = 626.5, 613.0  # mark bbox center in 1254 space
    dx, dy = 54 - cx * s, 54 - cy * s
    fg_paths = (
        "\n".join("            " + grad_path(rrect(*map(float, m))) for m in marks)
        + "\n            "
        + grad_path(re.sub(r"\s+", " ", swoosh).replace(" ,", ","))
    )
    fg = f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <!-- Designed MyWhisper mark, generated by scripts/make-icon.py -->
    <group
        android:scaleX="{s}"
        android:scaleY="{s}"
        android:translateX="{dx:.2f}"
        android:translateY="{dy:.2f}">
{fg_paths}
    </group>
</vector>
'''
    open(f"{OUT}/ic_launcher_foreground.xml", "w").write(fg)
    print("wrote background + foreground")


if __name__ == "__main__":
    sys.exit(main())
